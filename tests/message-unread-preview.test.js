import test from 'node:test';
import assert from 'node:assert/strict';
import { loadApp } from './helpers/app-harness.js';

test('inbox keeps the preview alongside the unread badge and clears the badge on open', async () => {
    const app = await loadApp();
    const { state } = app.exportsOf('src/core/state.js');
    const { conversations } = app.exportsOf('src/data/sample-data.js');
    const { renderMessages } = app.exportsOf('src/features/messages.js');
    const chat = conversations[0];
    const inbox = app.element('#messages-list');
    chat.lastMessage = 'Latest preview stays visible';
    chat.messages = [];
    chat.lastActivity = 1792738800000 - 10 * 60000;
    chat.unread = true;
    chat.unreadCount = 3;
    renderMessages();
    assert.match(inbox.innerHTML, /aria-label="3 unread messages">3</);
    assert.match(inbox.innerHTML, />10 min ago</);
    chat.unreadCount = 4;
    renderMessages();
    assert.match(inbox.innerHTML, /aria-label="4 unread messages">4</);
    chat.unreadCount = 7;
    renderMessages();
    assert.match(inbox.innerHTML, /aria-label="More than 4 unread messages">\+4</);
    assert.match(inbox.innerHTML, /conversation-preview">Latest preview stays visible</);
    state.activeConversationHandle = chat.handle;
    renderMessages();
    assert.equal(chat.unread, false);
    assert.equal(chat.unreadCount, 0);
    state.activeConversationHandle = null;
    renderMessages();
    assert.doesNotMatch(inbox.innerHTML, /More than 4 unread messages/);
});
